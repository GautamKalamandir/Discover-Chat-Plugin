def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=base["BodyText"], fontSize=9.5, leading=13, textColor=INK)
    return {
        "title": ParagraphStyle(
            "title", parent=base["Title"], fontSize=22, leading=26, alignment=0, textColor=INK
        ),
        "subtitle": ParagraphStyle(
            "subtitle", parent=body, fontSize=13, leading=17, textColor=MUTED, spaceAfter=6
        ),
        "h1": ParagraphStyle(
            "h1", parent=base["Heading1"], fontSize=15, leading=19, textColor=INK, spaceBefore=10
        ),
        "h2": ParagraphStyle(
            "h2", parent=base["Heading2"], fontSize=11.5, leading=15, textColor=INK, spaceBefore=8
        ),
        "body": body,
        "bold": ParagraphStyle("bold", parent=body, fontName="Helvetica-Bold"),
        "bullet": ParagraphStyle("bullet", parent=body, leftIndent=10, bulletIndent=2),
        "small": ParagraphStyle("small", parent=body, fontSize=8, leading=10.5, textColor=MUTED),
        "cell": ParagraphStyle("cell", parent=body, fontSize=8, leading=10),
        "num": ParagraphStyle("num", parent=body, fontSize=8, leading=10, alignment=2),
        "head": ParagraphStyle(
            "head", parent=body, fontSize=8, leading=10, fontName="Helvetica-Bold"
        ),
        "headnum": ParagraphStyle(
            "headnum", parent=body, fontSize=8, leading=10, fontName="Helvetica-Bold", alignment=2
        ),
    }


