def _cover(
    content: SummaryReportContent, company_name: str, logo_path: str | None, zone: ZoneInfo
) -> Iterator[Flowable]:
    logo = _logo(logo_path) if logo_path else None
    if logo is not None:
        yield logo
        yield Spacer(1, 3 * mm)
    yield _p(company_name, "title")
    yield _p("Daily MIS summary", "subtitle")
    generated = _local(content.generated_at, zone)
    who = f"Prepared for {content.user_name}. " if content.user_name else ""
    yield _p(f"{who}Generated {generated:%d %b %Y, %H:%M} ({content.timezone}).", "body")
    for note in content.notes:
        yield _p(note, "small")


def _overview(content: SummaryReportContent) -> Iterator[Flowable]:
    rows = content.overview or [
        OverviewRow(dataset_id=s.dataset_id, name=s.name, status=s.status, alert=s.message)
        for s in content.sections
    ]
    yield _p("All data sources at a glance", "h1")
    table: list[list[Any]] = [
        [
            _p("Data source", "head"),
            _p("Data for", "head"),
            _p("Main KPI", "head"),
            _p("Value", "headnum"),
            _p("vs previous", "headnum"),
            _p("Needs attention", "head"),
        ]
    ]
    for row in rows:
        if row.status != "ok":
            table.append(
                [
                    _p(row.name, "cell"),
                    _p("", "cell"),
                    _p(STATUS_TEXT[row.status], "cell"),
                    "",
                    "",
                    _p(row.alert or "", "small"),
                ]
            )
            continue
        table.append(
            [
                _p(row.name, "cell"),
                _p(_short_day(row.data_date), "cell"),
                _p(row.kpi_label or "", "cell"),
                _p(compact_indian(row.value), "num"),
                _coloured(_percent_words(row.change_percent), row.good, "num"),
                _p(row.alert or "", "cell"),
            ]
        )
    widths = [38 * mm, 18 * mm, 30 * mm, 22 * mm, 24 * mm]
    yield _table(table, [*widths, CONTENT_WIDTH - sum(widths)])


def _summary(content: SummaryReportContent) -> Iterator[Flowable]:
    yield _p("Executive summary", "h1")
    yield from _text(content.summary)


def _actions(content: SummaryReportContent) -> Iterator[Flowable]:
    evidence = {s.name: _evidence_index(s) for s in content.sections}
    everything = [x for s in content.sections for x in s.suggestions]
    heading = _p("Action points", "h1")
    if not everything:
        yield KeepTogether([heading, _p("No action points for today.", "body")])
        return
    first = True
    for priority in ("high", "medium", "low"):
        chosen = [x for x in everything if x.priority == priority]
        if not chosen:
            continue
        style = ParagraphStyle(
            f"h2-{priority}", parent=STYLES["h2"], textColor=PRIORITY_COLOURS[priority]
        )
        title = Paragraph(f"{priority.capitalize()} priority ({len(chosen)})", style)
        for index, suggestion in enumerate(chosen):
            box = _action_box(suggestion, evidence.get(suggestion.model_name, {}))
            lead = ([heading] if first else []) + ([title] if index == 0 else [])
            yield KeepTogether([*lead, box, Spacer(1, 2.5 * mm)])  # headings stay with a box
            first = False


def _action_box(suggestion: Suggestion, evidence: dict[str, str]) -> Flowable:
    meta = [f"Data source: {suggestion.model_name}"]
    if suggestion.where:
        meta.append(f"Where: {suggestion.where}")
    if suggestion.owner:
        meta.append(f"Who: {suggestion.owner}")
    meta.append(f"By: {URGENCY_TEXT[suggestion.urgency]}")
    parts: list[Flowable] = [
        _p(suggestion.title, "bold"),
        _p("  |  ".join(meta), "small"),
        _p(suggestion.reason, "body"),
    ]
    if suggestion.notes:
        parts.append(_p(f"Notes: {suggestion.notes}", "body"))
    for figure in (evidence[e] for e in suggestion.evidence if e in evidence):
        parts.append(Paragraph(_escape(figure), STYLES["small"], bulletText="•"))
    box = Table([[parts]], colWidths=[CONTENT_WIDTH])
    box.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), PANEL_BG),
                ("LINEBEFORE", (0, 0), (0, -1), 3, PRIORITY_COLOURS[suggestion.priority]),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    return box


