"""Renders a /summary report as a PDF (ADR 0015 and amendment 1, design §5 and §9). ReportLab with
its built-in Helvetica.

Layout for MIS executives and upper management:
- page 1: cover, "All data sources at a glance", executive summary, action points (what, where,
  who, by when) grouped High / Medium / Low with the figures behind them;
- then one part per data source with figures (each on a new page): KPI table with actual values
  and changes coloured by the KPI's direction (green = better, red = needs attention), KPI change
  overview, daily trend, top and bottom performers, target achievement, "No activity now", the
  narrative and further explained changes;
- data sources without figures are listed together at the end.

ReportLab paragraph text is markup, so every string from the LLM or the data is escaped before it
reaches a Paragraph: report text can't change fonts or add links. Rendering is CPU work; callers
run it in a thread.
"""

