def _section(section: ModelSection, zone: ZoneInfo) -> Iterator[Flowable]:
    details = []
    if section.data_date:
        details.append(f"Figures for {day_label(section.data_date)}")
    if section.refreshed_at:
        details.append(f"data refreshed {_local(section.refreshed_at, zone):%d %b %Y, %H:%M}")
    header: list[Flowable] = [_p(section.name, "h1")]
    if details:
        header.append(_p(" | ".join(details), "small"))
    if section.headline:
        header += [Spacer(1, 2 * mm), _p(section.headline, "bold")]
    if section.kpis:
        header += [Spacer(1, 2 * mm), _kpi_table(section.kpis, section.data_date)]
    if section.missing_kpis:
        header.append(_p("No value on this day: " + ", ".join(section.missing_kpis) + ".", "small"))
    yield KeepTogether(header)

    overview = _kpi_change_chart(section.kpis)
    if overview is not None:
        yield _chart_block("How each KPI changed (% change)", overview, _change_legend())
    if section.narrative:
        yield Spacer(1, 2 * mm)
        yield from _text(section.narrative)
    if section.trend is not None:
        chart = _trend_chart(section.trend)
        if chart is not None:
            title = f"Daily trend: {section.trend.kpi_label}"
            yield _chart_block(title, chart, _trend_legend(section.trend))
    if section.performers:
        better = section.kpis[0].higher_is_better if section.kpis else True
        main = section.kpis[0].label if section.kpis else ""
        period = f", {section.performers_period}" if section.performers_period else ""
        for breakdown in section.performers:
            chart = _driver_chart(breakdown, better)
            if chart is not None:
                title = f"Top and bottom by {breakdown.by}: {main}{period}"
                yield _chart_block(title, chart, _share_legend())
    targets = _target_chart(section.kpis)
    if targets is not None:
        yield _chart_block("Target achievement (%)", targets, _target_legend())
    if section.inactive:
        yield from _inactive(section.inactive)
    for analysis in section.focus:
        better = next((k.higher_is_better for k in section.kpis if k.id == analysis.kpi_id), True)
        yield from _focus(analysis, better)
    if section.assumptions:
        yield Spacer(1, 2 * mm)
        yield _p("Assumptions: " + "; ".join(section.assumptions), "small")
    yield _p(
        "Figures show what happened and where in the data; the data can't show outside reasons.",
        "small",
    )


def _kpi_table(rows: list[KpiRow], data_date: date | None) -> Table:
    labels = {c.baseline: c.label for row in rows for c in row.comparisons}
    has_prev = any("prev_day" in {c.baseline for c in r.comparisons} for r in rows)
    has_target = any(r.achievement_day is not None or r.achievement_mtd is not None for r in rows)
    head = [
        _p("KPI", "head"),
        _p(day_label(data_date) if data_date else "Latest day", "headnum"),
    ]
    if has_prev:
        head.append(_p(f"Previous day {labels['prev_day'].removeprefix('vs ')}", "headnum"))
    head += [
        _p(f"Same day last week {labels.get('week_ago', '').removeprefix('vs ')}", "headnum"),
        _p("Month to date (vs same days last month)", "headnum"),
    ]
    if has_target:
        head.append(_p("Target achievement (day / month)", "headnum"))
    table: list[list[Any]] = [head]
    for row in rows:
        by = {c.baseline: c for c in row.comparisons}
        cells: list[Any] = [_p(row.label, "cell"), _p(format_indian(row.value), "num")]
        if has_prev:
            cells.append(_compare_cell(by.get("prev_day"), row.higher_is_better, show="baseline"))
        cells.append(_compare_cell(by.get("week_ago"), row.higher_is_better, show="baseline"))
        cells.append(_compare_cell(by.get("mtd"), row.higher_is_better, show="current"))
        if has_target:
            cells.append(_achievement_cell(row))
        table.append(cells)
    count = len(head) - 2
    rest = (CONTENT_WIDTH - 36 * mm - 26 * mm) / max(count, 1)
    return _table(table, [36 * mm, 26 * mm] + [rest] * count)


def _compare_cell(c: KpiComparison | None, higher_is_better: bool, *, show: str) -> Any:
    """The comparison's own value on top, the change below it, coloured by direction."""
    if c is None:
        return ""
    value = c.baseline_value if show == "baseline" else c.current_value
    change = (
        _percent_words(c.percent_change)
        if c.percent_change is not None
        else (_change_words_short(c.change))
    )
    colour = _colour(_good(c.change, higher_is_better))
    text = f"{_escape(format_indian(value))}<br/><font color='{colour}'>{_escape(change)}</font>"
    return Paragraph(text, STYLES["num"])


def _achievement_cell(row: KpiRow) -> Any:
    if row.achievement_day is None and row.achievement_mtd is None:
        return ""  # this KPI has no target
    parts = []
    for value in (row.achievement_day, row.achievement_mtd):
        if value is None:
            parts.append("n/a")
        else:
            colour = _colour(value >= 100 if row.higher_is_better else value <= 100)
            parts.append(f"<font color='{colour}'>{value:.1f}%</font>")
    return Paragraph(" / ".join(parts), STYLES["num"])


def _inactive(blocks: list[InactiveBreakdown]) -> Iterator[Flowable]:
    lookback = blocks[0].lookback_days
    title = _p(f"No activity now (had a value in the previous {lookback} days)", "h2")
    table: list[list[Any]] = [
        [_p("By", "head"), _p("Item", "head"), _p("KPI", "head"), _p("Before", "headnum")]
    ]
    for block in blocks:
        for item in block.items[:MAX_INACTIVE_ROWS]:
            table.append(
                [
                    _p(block.by, "cell"),
                    _p(item.item, "cell"),
                    _p(block.kpi_label, "cell"),
                    _p(format_indian(item.baseline_value), "num"),
                ]
            )
        hidden = block.total - min(len(block.items), MAX_INACTIVE_ROWS)
        if hidden > 0 or block.truncated:
            more = f"and {hidden} more" if hidden > 0 else "list may be incomplete"
            table.append([_p(block.by, "cell"), _p(more, "small"), "", ""])
    widths = [32 * mm, 70 * mm, 40 * mm]
    yield KeepTogether([title, _table(table, [*widths, CONTENT_WIDTH - sum(widths)])])


def _focus(analysis: FocusAnalysis, higher_is_better: bool) -> Iterator[Flowable]:
    title = (
        f"What changed: {analysis.kpi_label}, {analysis.current_period} "
        f"vs {analysis.baseline_period}"
    )
    summary = (
        f"From {format_indian(analysis.baseline_value)} to "
        f"{format_indian(analysis.current_value)}: "
        f"{_change_words_short(analysis.change)}"
        + (f" ({_percent_words(analysis.percent_change)})" if analysis.percent_change else "")
        + "."
    )
    parts: list[Flowable] = [_p(title, "h2"), _p(summary, "body")]
    first = True
    for breakdown in analysis.breakdowns:
        chart = _driver_chart(breakdown, higher_is_better)
        if chart is None:
            continue
        block = [Spacer(1, 2 * mm), _p(f"By {breakdown.by}", "small"), chart]
        if first:  # keep the heading with its first chart
            yield KeepTogether([*parts, *block])
            first = False
        else:
            yield KeepTogether(block)
    if first:
        yield KeepTogether(parts)
    for note in analysis.notes:
        yield _p(note, "small")


def _not_included(sections: list[ModelSection]) -> Iterator[Flowable]:
    others = [s for s in sections if s.status != "ok"]
    if not others:
        return
    table: list[list[Any]] = [[_p("Data source", "head"), _p("Why", "head")]]
    table += [[_p(s.name, "cell"), _p(s.message or STATUS_TEXT[s.status], "cell")] for s in others]
    yield Spacer(1, 4 * mm)
    yield KeepTogether(
        [
            _p("Data sources without figures today", "h1"),
            _table(table, [60 * mm, CONTENT_WIDTH - 60 * mm]),
        ]
    )


