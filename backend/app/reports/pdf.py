def _chart_block(title: str, chart: Drawing, legend: str | None = None) -> Flowable:
    parts: list[Flowable] = [Spacer(1, 3 * mm), _p(title, "h2"), chart]
    if legend:
        parts.append(_p(legend, "small"))
    return KeepTogether(parts)


def _bar_chart(
    names: list[str], series: list[list[float]], height_per_row: float = 7 * mm
) -> tuple[Drawing, HorizontalBarChart]:
    rows = len(names)
    label_width, value_room = 62 * mm, 6 * mm
    plot_height = rows * height_per_row * max(len(series), 1) * 0.75 + rows * 2
    drawing = Drawing(CONTENT_WIDTH, plot_height + 12 * mm)
    chart = HorizontalBarChart()
    chart.x, chart.y = label_width, 8 * mm
    chart.width = CONTENT_WIDTH - label_width - value_room
    chart.height = plot_height
    chart.data = series
    chart.categoryAxis.categoryNames = names
    chart.categoryAxis.labelAxisMode = "low"  # at the left edge, not on the zero line
    chart.categoryAxis.labels.fontName = "Helvetica"
    chart.categoryAxis.labels.fontSize = 7.5
    chart.categoryAxis.labels.boxAnchor = "e"
    chart.categoryAxis.labels.dx = -4
    chart.categoryAxis.visibleTicks = 0
    chart.categoryAxis.strokeColor = RULE
    values = [v for s in series for v in s]
    low, high = min(0.0, *values), max(0.0, *values)
    pad = (high - low) * 0.08 or 1.0
    chart.valueAxis.valueMin = low - (pad if low < 0 else 0)
    chart.valueAxis.valueMax = high + (pad if high > 0 else 0)
    chart.valueAxis.labels.fontName = "Helvetica"
    chart.valueAxis.labels.fontSize = 7
    chart.valueAxis.strokeColor = RULE
    chart.valueAxis.gridStrokeColor = RULE
    chart.valueAxis.visibleGrid = 1
    chart.bars.strokeColor = None
    chart.groupSpacing = 4
    drawing.add(chart)
    return drawing, chart


def _driver_chart(breakdown: DriverBreakdown, higher_is_better: bool) -> Drawing | None:
    items: list[DriverItem] = sorted(
        {i.item: i for i in breakdown.biggest_decreases + breakdown.biggest_increases}.values(),
        key=lambda i: i.change,
    )  # ascending: drawn bottom to top, so the largest increase ends on top
    if not items or all(i.change == 0 for i in items):
        return None
    names = [
        f"{_short(clean_text(i.item))}  {_signed(compact_indian(i.change), i.change)}"
        + (f"  ({i.share_of_total_change:.0f}%)" if i.share_of_total_change is not None else "")
        for i in items
    ]
    drawing, chart = _bar_chart(names, [[i.change for i in items]])
    chart.valueAxis.labelTextFormat = compact_indian
    for index, item in enumerate(items):
        chart.bars[(0, index)].fillColor = _fill(_good(item.change, higher_is_better))
    return drawing


def _kpi_change_chart(rows: list[KpiRow]) -> Drawing | None:
    """% change of every KPI vs the previous day and vs the same day last week."""
    picked = [
        r
        for r in rows
        if any(c.percent_change is not None for c in r.comparisons if c.baseline in _DAY_BASES)
    ]
    if not picked:
        return None
    picked = list(reversed(picked))  # first KPI on top
    series: list[list[float]] = []
    keys = [b for b in _DAY_BASES if any(b in {c.baseline for c in r.comparisons} for r in picked)]
    for key in keys:
        series.append(
            [
                next((c.percent_change or 0.0 for c in r.comparisons if c.baseline == key), 0.0)
                for r in picked
            ]
        )
    drawing, chart = _bar_chart([_short(r.label, 34) for r in picked], series, 6 * mm)
    chart.valueAxis.labelTextFormat = _percent_axis(series)
    for s, key in enumerate(keys):
        for index, row in enumerate(picked):
            c = next((c for c in row.comparisons if c.baseline == key), None)
            good = _good(c.change, row.higher_is_better) if c else None
            chart.bars[(s, index)].fillColor = _fill(good, light=s > 0)
    return drawing


_DAY_BASES = ("prev_day", "week_ago")


def _trend_chart(trend: Trend) -> Drawing | None:
    current = [p.value for p in trend.days]
    if sum(v is not None for v in current) < 2:
        return None
    earlier = [p.earlier_value for p in trend.days]
    height = 46 * mm
    drawing = Drawing(CONTENT_WIDTH, height + 10 * mm)
    chart = HorizontalLineChart()
    chart.x, chart.y = 20 * mm, 8 * mm
    chart.width, chart.height = CONTENT_WIDTH - 24 * mm, height
    chart.data = [current, earlier]
    step = max(len(trend.days) // 6, 1)
    chart.categoryAxis.categoryNames = [
        f"{p.day:%d %b}" if (len(trend.days) - 1 - i) % step == 0 else ""
        for i, p in enumerate(trend.days)
    ]
    chart.categoryAxis.labels.fontName = "Helvetica"
    chart.categoryAxis.labels.fontSize = 7
    chart.categoryAxis.strokeColor = RULE
    chart.categoryAxis.visibleTicks = 0
    values = [v for v in current + earlier if v is not None]
    low, high = min(values), max(values)
    pad = (high - low) * 0.1 or abs(high) * 0.1 or 1.0
    chart.valueAxis.valueMin = min(0.0, low - pad) if low >= 0 and low - pad < 0 else low - pad
    chart.valueAxis.valueMax = high + pad
    chart.valueAxis.labels.fontName = "Helvetica"
    chart.valueAxis.labels.fontSize = 7
    chart.valueAxis.labelTextFormat = compact_indian
    chart.valueAxis.strokeColor = RULE
    chart.valueAxis.gridStrokeColor = RULE
    chart.valueAxis.visibleGrid = 1
    chart.lines[0].strokeColor = ACCENT
    chart.lines[0].strokeWidth = 1.8
    chart.lines[1].strokeColor = EARLIER
    chart.lines[1].strokeWidth = 1
    chart.lines[1].strokeDashArray = [3, 2]
