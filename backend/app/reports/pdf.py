def render_pdf(
    content: SummaryReportContent,
    *,
    company_name: str,
    logo_path: str | None = None,
    compress: bool = True,
) -> bytes:
    """The report as PDF bytes. `compress=False` keeps page text searchable (tests)."""
    zone = ZoneInfo(content.timezone)
    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
        topMargin=MARGIN,
        bottomMargin=20 * mm,
        title=f"Daily summary {_local(content.generated_at, zone):%d %b %Y}",
        author=company_name,
        subject="Daily summary",
        creator="Discover Chat Bot",
        pageCompression=1 if compress else 0,
        invariant=1,  # no embedded creation time or random ids: same input, same file
    )
    story = [
        *_cover(content, company_name, logo_path, zone),
        *_overview(content),
        *_summary(content),
        *_actions(content),
    ]
    for section in content.sections:
        if section.status == "ok":
            # A data source starts on a new page unless most of the current one is free.
            story += [CondPageBreak(SECTION_ROOM), *_section(section, zone)]
    story += list(_not_included(content.sections))
    document.build(story, canvasmaker=_NumberedCanvas)
    pdf = buffer.getvalue()
    if len(pdf) > MAX_PDF_BYTES:
        raise ReportRenderError(f"report PDF is {len(pdf)} bytes")
    return pdf


