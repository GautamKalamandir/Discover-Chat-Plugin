# --- helpers -------------------------------------------------------------------------------------


def _good(change: float | None, higher_is_better: bool) -> bool | None:
    if not change:
        return None
    return (change > 0) == higher_is_better


def _colour(good: bool | None) -> str:
    if good is None:
        return "#57606a"
    return "#1a7f37" if good else "#b42318"


def _fill(good: bool | None, *, light: bool = False) -> colors.Color:
    if good is None:
        return NEUTRAL
    if light:
        return GOOD_LIGHT if good else BAD_LIGHT
    return GOOD if good else BAD


def _coloured(text: str, good: bool | None, style: str) -> Paragraph:
    return Paragraph(f"<font color='{_colour(good)}'>{_escape(text)}</font>", STYLES[style])


def _percent_words(percent: float | None) -> str:
    if percent is None:
        return ""
    if percent == 0:
        return "no change"
    return f"{'up' if percent > 0 else 'down'} {abs(percent):.2f}%"


def _change_words_short(change: float | None) -> str:
    if change is None:
        return "n/a"
    if change == 0:
        return "no change"
    return f"{'up' if change > 0 else 'down'} {format_indian(abs(change))}"


def _signed(text: str, value: float) -> str:
    return f"+{text}" if value > 0 else text


def _short_day(day: date | None) -> str:
    return f"{day:%d %b}" if day else ""


def _evidence_index(section: ModelSection) -> dict[str, str]:
    """Fact id -> the figures it stands for, as shown under an action point."""
    index: dict[str, str] = {}
    for row in section.kpis:
        index[row.id] = f"{row.label}: {format_indian(row.value)}"
        for c in row.comparisons:
            change = _change_words_short(c.change) + (
                f" ({abs(c.percent_change):.2f}%)" if c.percent_change is not None else ""
            )
            index[c.fact_id] = (
                f"{row.label} {c.label}: {format_indian(c.current_value)} vs "
                f"{format_indian(c.baseline_value)}, {change}"
            )
    for f in section.focus:
        index[f.id] = (
            f"{f.kpi_label}, {f.current_period} vs {f.baseline_period}: "
            f"{_change_words_short(f.change)}"
        )
    if section.performers:
        index["performers"] = f"Top and bottom performers ({section.performers_period or ''})"
    if section.inactive:
        count = sum(b.total for b in section.inactive)
        index["no_activity_now"] = f"{count} item(s) with no activity on the latest day"
    if section.trend is not None:
        index["trend"] = f"Daily trend of {section.trend.kpi_label}"
    return index


def _text(text: str) -> Iterator[Flowable]:
    """Narrative text: '- ' lines become bullets, other lines paragraphs."""
    for line in (raw.strip() for raw in text.splitlines()):
        if not line:
            continue
        if line.startswith(("- ", "* ")):
            yield Paragraph(_escape(line[2:]), STYLES["bullet"], bulletText="•")
        else:
            yield _p(line, "body")


def _p(text: str, style: str) -> Paragraph:
    return Paragraph(_escape(text), STYLES[style])


def _escape(text: str) -> str:
    """Report text as plain paragraph text: no markup, and only characters the font can draw."""
    return escape(clean_text(text) if text else text).replace("\n", "<br/>")


def _table(rows: list[list[Any]], widths: list[float]) -> Table:
    table = Table(rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), HEADER_BG),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, RULE),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    return table


def _short(text: str, limit: int = 28) -> str:
    return text if len(text) <= limit else text[: limit - 3] + "..."


def _local(moment: datetime, zone: ZoneInfo) -> datetime:
    return moment.astimezone(zone)


def _logo(path: str) -> Image | None:
    file = Path(path)
    try:
        if not file.is_file() or file.stat().st_size > MAX_LOGO_BYTES:
            logger.warning("REPORT_LOGO_PATH is missing or larger than 2 MB; logo left out")
            return None
        logo = Image(str(file))
        height = 14 * mm
        width = min(height * logo.imageWidth / logo.imageHeight, 60 * mm)
        logo.drawHeight, logo.drawWidth = height, width
        logo.hAlign = "LEFT"
        return logo
    except Exception:
        logger.warning("REPORT_LOGO_PATH could not be read as an image; logo left out")
        return None


class _NumberedCanvas(Canvas):  # type: ignore[misc]
    """Footer with "Page x of y": pages are kept until the total is known."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._pages: list[dict[str, Any]] = []

    def showPage(self) -> None:  # noqa: N802 - ReportLab API
        self._pages.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        total = len(self._pages)
        for state in self._pages:
            self.__dict__.update(state)
            self.setFont("Helvetica", 7.5)
            self.setFillColor(MUTED)
            self.drawString(MARGIN, 10 * mm, FOOTER)
            self.drawRightString(A4[0] - MARGIN, 10 * mm, f"Page {self._pageNumber} of {total}")
            super().showPage()
        super().save()
