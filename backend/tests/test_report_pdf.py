@pytest.mark.parametrize(
    ("change", "higher_is_better", "good"),
    [
        (5.0, True, True),
        (-5.0, True, False),
        (5.0, False, False),
        (-5.0, False, True),
        (0, True, None),
    ],
)
def test_colours_follow_each_kpis_direction(
    change: float, higher_is_better: bool, good: bool | None
) -> None:
    assert pdf_module._good(change, higher_is_better) is good
    expected = {True: "#1a7f37", False: "#b42318", None: "#57606a"}[good]
    assert pdf_module._colour(good) == expected


def test_percent_axes_avoid_duplicate_zero_labels() -> None:
    small = pdf_module._percent_axis([[-0.58, -1.83]])
    large = pdf_module._percent_axis([[-20.0, 25.0]])

    assert (small(-0.01), small(-1.5), large(-20.0)) == ("0.0%", "-1.5%", "-20%")
