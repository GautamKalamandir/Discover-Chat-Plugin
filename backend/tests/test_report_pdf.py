@pytest.mark.scenario(12)
def test_text_from_the_llm_or_the_data_cannot_add_links_or_markup() -> None:
    pdf = render(content(sales_section(HOSTILE, name=f"Sales {HOSTILE}"), summary=HOSTILE))

    assert b"/URI" not in pdf and b"/JavaScript" not in pdf and b"/Annot" not in pdf
    # Shown as plain text (ReportLab splits the run at each escaped character).
    assert b"(<) Tj (a href='javascript:alert\\(1\\)') Tj (>) Tj (click) Tj" in pdf
    assert b"/F1 90" not in pdf  # no 90-point font from the injected <font size=90>


