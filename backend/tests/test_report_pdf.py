def full_section() -> ModelSection:
    """A schema-2 section: trend, performers, target, no-activity items, a missing KPI."""
    base = sales_section()
    kpis = [
        base.kpis[0].model_copy(update={"achievement_day": 86.6, "achievement_mtd": 104.2}),
        KpiRow(
            id="k2",
            label="Sales returns",
            value=300.0,
            higher_is_better=False,
            comparisons=[comparison("k2.prev_day", "prev_day", -50.0)],
        ),
    ]
    return base.model_copy(
        update={
            "kpis": kpis,
            "missing_kpis": ["GV Conversion %"],
            "trend": Trend(
                kpi_label="Net sales",
                days=[
                    TrendPoint(day=date(2026, 10, d), value=1000.0 + d * 10, earlier_value=900.0)
                    for d in range(1, 13)
                ],
            ),
            "performers": [
                DriverBreakdown(
                    by="Location",
                    biggest_decreases=[item("STR - SURAT", -707900.0)],
                    biggest_increases=[item("STR - VAPI", 102100.0)],
                )
            ],
            "performers_period": "12 Oct 2026 vs 05 Oct 2026",
            "inactive": [
                InactiveBreakdown(
                    by="Location",
                    kpi_label="Net sales",
                    lookback_days=7,
                    items=[InactiveItem(item="STR - UDHNA", baseline_value=1250000.0)],
                    total=15,
                )
            ],
            "suggestions": [
                Suggestion(
                    priority="high",
                    title="Find out why STR - UDHNA had no sales",
                    where="STR - UDHNA",
                    owner="Store operations",
                    urgency="today",
                    reason="No sales on 12 Oct.",
                    evidence=["no_activity_now"],
                    model_name="Sales",
                )
            ],
        }
    )


