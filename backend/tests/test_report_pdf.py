HOSTILE = "<a href='javascript:alert(1)'>click</a> <font size=90>big</font> & </para>"


def comparison(fact_id: str, baseline: Baseline, change: float) -> KpiComparison:
    return KpiComparison(
        fact_id=fact_id,
        baseline=baseline,
        label="vs 05 Oct 2026",
        current_value=1000.0 + change,
        baseline_value=1000.0,
        change=change,
        percent_change=change / 10,
    )


def item(name: str, change: float) -> DriverItem:
    return DriverItem(
        item=name,
        baseline_value=500.0,
        current_value=500.0 + change,
        change=change,
        percent_change=change / 5,
        share_of_total_change=50.0,
    )


def sales_section(text: str = "Net sales fell.", name: str = "Sales") -> ModelSection:
    return ModelSection(
        dataset_id="sales-ds",
        name=name,
        status="ok",
        data_date=date(2026, 10, 12),
        refreshed_at=datetime(2026, 10, 13, 0, 40, tzinfo=UTC),
        kpis=[
            KpiRow(
                id="k1",
                label="Net sales",
                value=1234567.89,
                comparisons=[
                    comparison("k1.prev_day", "prev_day", -100.5),
                    comparison("k1.week_ago", "week_ago", 250.0),
                ],
            )
        ],
        focus=[
            FocusAnalysis(
                id="f1",
                kpi_id="k1",
                kpi_label="Net sales",
                baseline="week_ago",
                baseline_period="05 Oct 2026",
                current_period="12 Oct 2026",
                baseline_value=1000.0,
                current_value=1250.0,
                change=250.0,
                percent_change=25.0,
                breakdowns=[
                    DriverBreakdown(
                        by="Store",
                        biggest_decreases=[item("Store A", -80.0)],
                        biggest_increases=[item("Store B", 330.0)],
                    )
                ],
            )
        ],
        headline=f"Headline: {text}",
        narrative=f"{text}\n- First point\n- Second point",
        suggestions=[
            Suggestion(
                priority="high",
                title=f"Review {text}",
                reason="Because 250 more.",
                notes=text,
                evidence=["k1.week_ago", "f1"],
                model_name=name,
            ),
            Suggestion(
                priority="low",
                title="Minor thing",
                reason="Small change.",
                evidence=["k1.prev_day"],
                model_name=name,
            ),
        ],
        assumptions=["Net sales means Total Net Sales."],
    )


def content(*sections: ModelSection, summary: str = "All good.") -> SummaryReportContent:
    return SummaryReportContent(
        report_id=uuid.uuid4(),
        generated_at=datetime(2026, 10, 13, 3, 5, tzinfo=UTC),
        timezone="Asia/Kolkata",
        user_name="User A",
        summary=summary,
        sections=list(sections) or [sales_section()],
        notes=["Development data, not real figures."],
    )


def render(report: SummaryReportContent, **kwargs: object) -> bytes:
    return render_pdf(report, company_name="Acme Jewels", compress=False, **kwargs)  # type: ignore[arg-type]


def pages(pdf: bytes) -> int:
    return len(re.findall(rb"/Type /Page\b", pdf))


def test_a_report_renders_as_a_pdf_with_every_part() -> None:
    pdf = render(content())

    assert pdf.startswith(b"%PDF-")
    assert pages(pdf) >= 1
    for text in (
        b"Acme Jewels",
        b"Daily summary",
        b"Prepared for User A",
        b"13 Oct 2026, 08:35",  # generated time in the report's time zone (IST)
        b"Executive summary",
        b"High priority \\(1\\)",
        b"Low priority \\(1\\)",
        b"Review Net sales fell.",
        b"12,34,567.89",  # Indian grouping
        b"By Store",
        b"Store B  +330",
        b"Development data, not real figures.",
        b"Generated by Discover Chat Bot from your Power BI data",
        b"Page 1 of",
    ):
        assert text in pdf, text


