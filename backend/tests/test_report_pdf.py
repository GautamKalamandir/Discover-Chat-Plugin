def test_the_logo_is_shown_when_configured(tmp_path: Path) -> None:
    logo = tmp_path / "logo.png"
    PILImage.new("RGB", (40, 20), "navy").save(logo)
    assert ImageReader(str(logo)).getSize() == (40, 20)

    with_logo = render(content(), logo_path=str(logo))

    assert b"/Subtype /Image" in with_logo
    assert b"/Subtype /Image" not in render(content())


@pytest.mark.parametrize("logo", ["missing.png", "not-an-image.png", "huge.png"])
def test_an_unusable_logo_is_left_out_without_failing(tmp_path: Path, logo: str) -> None:
    (tmp_path / "not-an-image.png").write_text("this is not a picture")
    (tmp_path / "huge.png").write_bytes(b"\0" * (pdf_module.MAX_LOGO_BYTES + 1))

    pdf = render(content(), logo_path=str(tmp_path / logo))

    assert pdf.startswith(b"%PDF-") and b"/Subtype /Image" not in pdf


def test_a_pdf_over_the_download_limit_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    assert MAX_PDF_BYTES == 30 * 1024 * 1024  # Power BI's limit for visual downloads
    monkeypatch.setattr(pdf_module, "MAX_PDF_BYTES", 1000)

    with pytest.raises(ReportRenderError):
        render(content())


